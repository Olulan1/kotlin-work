fun main() {
	val myAge = 29u
	val universeAge = 13_800_000_000L
	val status = 'M'
	val name = "Sarah"
	val height = 1.78f
	val root2 = Math.sqrt(2.0)
	print("\n myAge: ")
	println(myAge::class)
	print("\n universeAge: ")
	println(universeAge::class)
	print("\n status: ")
	println(status::class)
	print("\n name: ")
	println(name::class)
	print("\n height: ")
	println(height::class)
	print("\n root2: ")
	println(root2::class)
	
	val pi: Double = 3.14159
	print("\n pi: "+pi+" ")
	println(pi::class)
	
}
